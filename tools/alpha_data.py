def specs():
    """gen.py で動画にするための仕様(キーは 'u_A' / 'l_a')。"""
    out = {}
    for tag, table in (('u', U), ('l', L)):
        for ch, (paths, rows) in table.items():
            write = []
            for p in paths:
                ln = sum(math.hypot(b[0] - a[0], b[1] - a[1]) for a, b in zip(p[:-1], p[1:]))
                write.append(round(min(2.2, max(0.9, 0.7 + ln / 650)), 1))
            out[f'{tag}_{ch}'] = dict(ch=ch, paths=paths, rows=rows, write=write, cross=[], badge={}, quick=True,
                                      mono=True, lw=36)
    return out
