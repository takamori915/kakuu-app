# assign: (画の番号, (x0, x1, y0, y1), 時間を0にするか) … その長方形の中を、その画に決め打ちする
# cross : (先に書く画, 後に書く画, (x0, x1, y0, y1)) … 2つの画が交わる所。後の画が通るとき、そこも青くなる
import numpy as np


def _len(p):
    a = np.array(p, float)
    return float(np.hypot(*np.diff(a, axis=0).T).sum())


def _spec(ch, paths, rows, **kw):
    write = [round(min(1.8, max(1.0, _len(p) / 260)), 1) for p in paths]
    s = dict(ch=ch, paths=paths, rows=rows, write=write, cross=[], badge={}, size=525)
    s.update(kw)
    return s


